// 供全站搜尋使用的攤平索引
function flattenCurriculum() {
  const list = [];
  Object.values(CURRICULUM).forEach((subject) => {
    subject.units.forEach((unit) => {
      unit.topics.forEach((topic) => {
        list.push({
          subjectKey: subject.key,
          subjectTitle: subject.title,
          unitId: unit.id,
          unitTitle: unit.title,
          ...topic,
        });
      });
    });
  });
  return list;
}
